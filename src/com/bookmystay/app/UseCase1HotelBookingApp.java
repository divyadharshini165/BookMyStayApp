package com.bookmystay.app;

/**
 * Book My Stay Application
 *
 * <p>This class represents the entry point of the Hotel Booking Management System.
 * It demonstrates how a Java application starts execution using the main method
 * and prints a welcome message to the console.</p>
 *
 * @author Divya
 * @version 1.0
 */
public class UseCase1HotelBookingApp {

    /**
     * Application entry point.
     * JVM starts execution from this method.
     *
     * @param args command line arguments
     */
    public static void main(String[] args) {

        System.out.println("===================================");
        System.out.println("     Welcome to Book My Stay App    ");
        System.out.println("     Hotel Booking System v1.0      ");
        System.out.println("===================================");

        System.out.println("Application started successfully...");
        System.out.println("Application terminated.");
    }
}